def sum(a, b):
    """Additionne deux nombres.

    :param a: premier nombre
    :param b: second nombre
    :return: la somme de a et b
    """
    return a + b


def subtraction(a, b):
    """Soustrait b à a.

    :param a: premier nombre
    :param b: nombre à soustraire
    :return: la différence a - b
    """
    return a - b
